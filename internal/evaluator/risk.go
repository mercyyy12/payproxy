package evaluator

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"time"
)

// calls Gemini to inspect transactions for semantic fraud
type Evaluator struct {
	apiKey     string
	httpClient *http.Client
}

// response returned by the AI
type RiskAssessment struct {
	RiskScore int    `json:"risk_score"`
	Flagged   bool   `json:"flagged"`
	Reason    string `json:"reason"`
}

type geminiPart struct {
	Text string `json:"text"`
}

type geminiContent struct {
	Parts []geminiPart `json:"parts"`
}

type geminiConfig struct {
	ResponseMimeType string `json:"response_mime_type"`
}

type geminiRequest struct {
	Contents         []geminiContent `json:"contents"`
	GenerationConfig geminiConfig    `json:"generationConfig"`
}

type geminiResponse struct {
	Candidates []struct {
		Content struct {
			Parts []struct {
				Text string `json:"text"`
			} `json:"parts"`
		} `json:"content"`
	} `json:"candidates"`
}

// initializes the AI risk evaluator
func NewEvaluator(apiKey string) *Evaluator {
	return &Evaluator{
		apiKey: apiKey,
		httpClient: &http.Client{
			Timeout: 8 * time.Second,
		},
	}
}

// asks Gemini if the merchant matches the stated purpose
func (e *Evaluator) Assess(ctx context.Context, merchant, purpose string) (*RiskAssessment, error) {
	if e.apiKey == "" {
		return nil, fmt.Errorf("security check unavailable: GEMINI_API_KEY is not configured")
	}

	prompt := fmt.Sprintf(
		"You are a strict financial security auditor for autonomous AI agents. "+
			"An AI agent wants to spend company funds. "+
			"Merchant: '%s'. Stated Purpose: '%s'. "+
			"Does this merchant legitimately provide what the stated purpose claims? "+
			"Evaluate if this is legitimate, suspicious, or completely mismatched. "+
			"Return JSON with: "+
			"\"risk_score\" (integer 0 to 100, where 0 is completely safe and 100 is blatant fraud), "+
			"\"flagged\" (boolean, true if risk_score > 50), "+
			"\"reason\" (one concise sentence explaining your verdict).",
		merchant, purpose,
	)

	// assemble gemini payload requesting strict JSON output
	payload := geminiRequest{
		Contents: []geminiContent{
			{
				Parts: []geminiPart{{Text: prompt}},
			},
		},
		GenerationConfig: geminiConfig{
			ResponseMimeType: "application/json",
		},
	}

	jsonData, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal gemini request: %w", err)
	}

	url := "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent?key=" + e.apiKey
	req, err := http.NewRequestWithContext(ctx, "POST", url, bytes.NewReader(jsonData))
	if err != nil {
		return nil, fmt.Errorf("failed to create gemini request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	// send request to gemini
	resp, err := e.httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to call gemini api: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(resp.Body)
		return nil, fmt.Errorf("gemini api error (status %d): %s", resp.StatusCode, string(body))
	}

	// parse gemini wrapper response
	var gResp geminiResponse
	if err := json.NewDecoder(resp.Body).Decode(&gResp); err != nil {
		return nil, fmt.Errorf("failed to decode gemini response: %w", err)
	}

	if len(gResp.Candidates) == 0 || len(gResp.Candidates[0].Content.Parts) == 0 {
		return nil, fmt.Errorf("gemini returned empty response")
	}

	// parse inner JSON verdict generated by the model
	rawJSON := gResp.Candidates[0].Content.Parts[0].Text
	var assessment RiskAssessment
	if err := json.Unmarshal([]byte(rawJSON), &assessment); err != nil {
		return nil, fmt.Errorf("failed to parse ai risk json: %w", err)
	}

	return &assessment, nil
}
